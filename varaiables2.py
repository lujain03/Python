# Dynamic Typed language : Python is a dynamic typed language, which means that you don't have to declare the type of a variable when you create it. The type of a variable is determined at runtime based on the value assigned to it.
x = 5 # integer
x = "Hello, World!" # string
print(x) # Hello, World!

# Reserved words : you can't use reserved words as variable names
