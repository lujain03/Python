# Theortical concepts of variables in python
# Source code : Original code written by Lujain in computer
# Translation : The code is translated into machine language by the compiler
# compilation : The process of translating the source code into machine language is called compilation
# Runtime : The time when the program is running is called runtime
# Interpreter : The program that translates the source code into machine language During runtime is called interpreter
